-- ATW-01g2: teams become ordered member lists (DUO/TRIO) and tournaments can take team entrants.
--
-- 1. team_member: the ordered membership child table (slot 0..n-1). Slots replace the
--    wrestler1_id/wrestler2_id columns on team; slots 0/1 mirror the legacy pair.
-- 2. team gains team_size / origin / fans. fans is backfilled as the sum of member
--    fans in the team's universe at migration time (preserves ranking order on upgrade);
--    from then on it accrues at team level only.
-- 3. tournament_entry gains a nullable team_id (exactly one of wrestler_id / team_id set);
--    wrestler_id's NOT NULL (V127) is relaxed — the check below needs wrestler_id NULL for
--    team-only entries.
-- 4. tournament gains a nullable team_size (NULL = singles tournament).
-- 5. title gains a nullable team_size (NULL = singles title); TEAM titles backfill to DUO.
-- 6. title_reign gains a nullable team_id so champion-team matching is exact.
-- 7. team.wrestler1_id / wrestler2_id are dropped after the backfill.

-- 1) Ordered membership child table -------------------------------------------------
CREATE TABLE team_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL,
    wrestler_id BIGINT NOT NULL,
    slot INT NOT NULL,
    CONSTRAINT fk_tm_team FOREIGN KEY (team_id) REFERENCES team(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_tm_wrestler FOREIGN KEY (wrestler_id) REFERENCES wrestler(wrestler_id) ON DELETE CASCADE,
    CONSTRAINT uq_tm_team_slot UNIQUE (team_id, slot),
    CONSTRAINT uq_tm_team_wrestler UNIQUE (team_id, wrestler_id)
);

CREATE INDEX idx_tm_wrestler ON team_member(wrestler_id);

-- 2) Backfill memberships from the legacy pair (slot 0 = wrestler1, slot 1 = wrestler2)
INSERT INTO team_member (team_id, wrestler_id, slot)
SELECT team_id, wrestler1_id, 0 FROM team;

INSERT INTO team_member (team_id, wrestler_id, slot)
SELECT team_id, wrestler2_id, 1 FROM team;

-- 3) team.team_size / origin / fans
ALTER TABLE team ADD COLUMN team_size VARCHAR(16) NOT NULL DEFAULT 'DUO';
ALTER TABLE team ADD COLUMN origin VARCHAR(16) NOT NULL DEFAULT 'REGISTRY';
ALTER TABLE team ADD COLUMN fans BIGINT NOT NULL DEFAULT 0;

-- Seed team fans as the member-fan sum in the team's universe (one-time migration input;
-- the live ordering metric is team.fans from here on).
UPDATE team t
SET fans = COALESCE((
    SELECT SUM(ws.fans)
    FROM wrestler_state ws
    JOIN team_member tm ON tm.team_id = t.team_id AND tm.wrestler_id = ws.wrestler_id
    WHERE ws.universe_id = t.universe_id
), 0);

-- 4) Tournament team entrants --------------------------------------------------------
ALTER TABLE tournament_entry ADD COLUMN team_id BIGINT;
ALTER TABLE tournament_entry
    ADD CONSTRAINT fk_entry_team FOREIGN KEY (team_id) REFERENCES team(team_id);
-- Relax wrestler_id's NOT NULL (V127) so a team-only entry can exist — the exactly-one
-- CHECK below needs wrestler_id NULL when team_id is set.
ALTER TABLE tournament_entry ALTER COLUMN wrestler_id SET NULL;
ALTER TABLE tournament_entry ADD CONSTRAINT chk_entry_entrant_type
    CHECK ((wrestler_id IS NOT NULL AND team_id IS NULL) OR (wrestler_id IS NULL AND team_id IS NOT NULL));

ALTER TABLE tournament ADD COLUMN team_size VARCHAR(16) NULL;

-- 5) Title team size -----------------------------------------------------------------
ALTER TABLE title ADD COLUMN team_size VARCHAR(16) NULL;
UPDATE title SET team_size = 'DUO' WHERE championship_type = 'TEAM';

-- 6) Title reign team reference -------------------------------------------------------
ALTER TABLE title_reign ADD COLUMN team_id BIGINT;
ALTER TABLE title_reign
    ADD CONSTRAINT fk_reign_team FOREIGN KEY (team_id) REFERENCES team(team_id);

-- 7) Drop the legacy pair columns (backed up into team_member above)
ALTER TABLE team DROP COLUMN wrestler1_id;
ALTER TABLE team DROP COLUMN wrestler2_id;
