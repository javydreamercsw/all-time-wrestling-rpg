-- Named-trophy payoffs and explicit no-payoff tournaments.
-- trophy_name = the named trophy (e.g. "Dusty Cup"). Non-null marks a trophy tournament:
-- the winner lifts the trophy, no championship changes hands. NULL with no contender /
-- briefcase flag is the bragging-rights-only tournament (already representable pre-V165;
-- the column just makes the trophy kind explicit).
ALTER TABLE tournament ADD COLUMN trophy_name VARCHAR(255) NULL;

-- The trophy lineage: one row per completed trophy-tournament edition. A tournament edition
-- is stamped exactly once at completion (TournamentService.markWinner, idempotent), so the
-- lineage is one row per year for recurring trophies — "2026 Dusty Cup — winners" for AI
-- narration and the detail view's honors list.
CREATE TABLE trophy_reign (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL,
    trophy_name VARCHAR(255) NOT NULL,
    year_won INT NOT NULL,
    won_on DATE NOT NULL,
    winner_wrestler_id BIGINT,
    winner_team_id BIGINT,
    universe_id BIGINT,
    CONSTRAINT fk_tr_tournament FOREIGN KEY (tournament_id) REFERENCES tournament(tournament_id),
    CONSTRAINT fk_tr_wrestler FOREIGN KEY (winner_wrestler_id) REFERENCES wrestler(wrestler_id),
    CONSTRAINT fk_tr_team FOREIGN KEY (winner_team_id) REFERENCES team(team_id),
    CONSTRAINT fk_tr_universe FOREIGN KEY (universe_id) REFERENCES universe(id),
    CONSTRAINT uq_tr_tournament UNIQUE (tournament_id),
    CONSTRAINT chk_tr_winner CHECK (
        (winner_wrestler_id IS NOT NULL AND winner_team_id IS NULL)
        OR (winner_wrestler_id IS NULL AND winner_team_id IS NOT NULL)
    )
);

CREATE INDEX idx_tr_wrestler ON trophy_reign(winner_wrestler_id);
CREATE INDEX idx_tr_team ON trophy_reign(winner_team_id);
