package com.github.javydreamercsw.management.sync;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.github.javydreamercsw.management.config.JacksonConfig;
import java.nio.charset.StandardCharsets;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.ClassPathResource;

/**
 * Unit tests for {@link SeedFingerprintManifest}. All parsing goes through the production {@link
 * JacksonConfig} mapper — the loader must behave identically under the real ObjectMapper
 * configuration, never a bare {@code new ObjectMapper()}.
 */
class SeedFingerprintManifestTest {

  private static final String FINGERPRINT_A = "a1b2c3d4e5f60718".repeat(4);
  private static final String FINGERPRINT_B = "0123456789abcdef".repeat(4);

  private final ObjectMapper mapper = new JacksonConfig().objectMapper();

  @Test
  void loadAbsentManifestReturnsEmpty() {
    SeedFingerprintManifest manifest =
        SeedFingerprintManifest.load(
            mapper, new ClassPathResource("seed-manifest-fixtures/absent-manifest.json"));
    assertTrue(manifest.domains().isEmpty());
    assertTrue(manifest.domain("wrestler").isEmpty());
  }

  @Test
  void loadParsesDomains() {
    String json =
        """
        {
          "generatedAt": "2026-11-05T17:00:00Z",
          "domains": {
            "segment_type": {
              "One on One": "%s"
            },
            "wrestler": {
              "Jeff Hardy": "%s"
            }
          }
        }
        """
            .formatted(FINGERPRINT_A, FINGERPRINT_B);
    SeedFingerprintManifest manifest = load(json);
    assertEquals(2, manifest.domains().size());
    assertEquals(
        Map.of("One on One", FINGERPRINT_A), manifest.domain("segment_type").orElseThrow());
    assertEquals(Map.of("Jeff Hardy", FINGERPRINT_B), manifest.domain("wrestler").orElseThrow());
  }

  @Test
  void domainReturnsEmptyOptionalForUnknownDomain() {
    SeedFingerprintManifest manifest =
        SeedFingerprintManifest.of(Map.of("wrestler", Map.of("Jeff Hardy", FINGERPRINT_A)));
    assertTrue(manifest.domain("segment_type").isEmpty());
    assertFalse(manifest.domain("wrestler").isEmpty());
  }

  @Test
  void malformedJsonFallsBackToEmpty() {
    // Syntactically broken JSON.
    assertTrue(load("{ not json at all ").domains().isEmpty());
    // Well-formed JSON, wrong shape: "domains" field missing.
    assertTrue(load("{\"generatedAt\": \"2026-11-05T17:00:00Z\"}").domains().isEmpty());
    // Well-formed JSON, wrong shape: "domains" not an object.
    assertTrue(load("{\"domains\": [1, 2, 3]}").domains().isEmpty());
    // Well-formed JSON, wrong shape: a domain value is not an object.
    assertTrue(load("{\"domains\": {\"wrestler\": \"not-an-object\"}}").domains().isEmpty());
  }

  @Test
  void publicLoadReadsClasspathResourceLeniently() {
    // Production entry point: reads RESOURCE_PATH from the classpath. The committed manifest is
    // generated by a later task, so this must degrade to an empty manifest today — and must keep
    // working (non-null, never throwing) once the manifest is committed.
    SeedFingerprintManifest manifest =
        assertDoesNotThrow(() -> SeedFingerprintManifest.load(mapper));
    assertNotNull(manifest);
    assertNotNull(manifest.domains());
  }

  private SeedFingerprintManifest load(String json) {
    return SeedFingerprintManifest.load(
        mapper, new ByteArrayResource(json.getBytes(StandardCharsets.UTF_8)));
  }
}
